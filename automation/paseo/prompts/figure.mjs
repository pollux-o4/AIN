/** @param {{stage: string, pass?: string}} action @param {{plan: string, check: string, draw: string}} policy */
export function figureSpec(action, policy = objectPolicy()) {
  // 구성이 고른 스타일 · 없으면 기본값(anatomy) · ADR-0027
  const look = lookRules(action.style?.look);
  const example = figureOutputExamples[action.stage];
  if (action.stage === "figure_plan") return { ...PLAN_SPEC, example };
  if (action.stage === "figure_compose") return { ...composeSpec(policy), example };
  return {
    task: "사람이 선택한 위치 후보(candidates의 한 건)에 놓을 SVG 그림 한 장을 생성한다. 본문 수정이나 재작성은 제안하지 않는다.",
    steps: PASS_STEPS[action.pass ?? FIGURE_PASSES[0]]?.map((step) =>
      step
        .replace("{FINISH}", look.finish)
        .replace("{PREPARE}", look.prepare)
        .replace("{LOOK_MOTION}", look.motion),
    ),
    rules: generateCommon(policy, look),
    criteria: [
      "candidates의 id에 해당하는 그림이 하나 있고 svgFile에 실제로 저장한 파일의 절대 경로가 적혀 있는가",
      "draft에 없는 수치·사실·출처가 그림과 설명에 없는가",
      "라벨을 가려도 원인 → 결과가 읽히는가",
    ],
    guards: GENERATE_GUARDS,
    example,
  };
}
